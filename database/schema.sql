CREATE TABLE IF NOT EXISTS departamentos (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS funcionarios (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 departamento_id INTEGER NOT NULL REFERENCES departamentos(id),
 salario NUMERIC(12,2) NOT NULL CHECK (salario >= 0),
 admissao DATE NOT NULL,
 desligamento DATE,
 CHECK (desligamento IS NULL OR desligamento >= admissao)
);
CREATE TABLE IF NOT EXISTS clientes (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cidade VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS produtos (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 categoria VARCHAR(80) NOT NULL,
 custo_unitario NUMERIC(12,2) NOT NULL CHECK (custo_unitario >= 0),
 preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0)
);
CREATE TABLE IF NOT EXISTS pedidos (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_id INTEGER NOT NULL REFERENCES clientes(id),
 data_pedido DATE NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('concluido','cancelado','pendente'))
);
CREATE TABLE IF NOT EXISTS itens_pedido (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id INTEGER NOT NULL REFERENCES pedidos(id),
 produto_id INTEGER NOT NULL REFERENCES produtos(id),
 quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 preco_venda NUMERIC(12,2) NOT NULL CHECK (preco_venda >= 0),
 custo_unitario NUMERIC(12,2) NOT NULL CHECK (custo_unitario >= 0)
);
CREATE TABLE IF NOT EXISTS lancamentos_financeiros (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descricao VARCHAR(160) NOT NULL,
 categoria VARCHAR(80) NOT NULL,
 tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('receita','despesa')),
 valor NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
 data_vencimento DATE NOT NULL,
 data_pagamento DATE
);
CREATE INDEX IF NOT EXISTS idx_pedidos_data ON pedidos(data_pedido);
CREATE INDEX IF NOT EXISTS idx_lancamentos_pagamento ON lancamentos_financeiros(data_pagamento);
